static inline uint16_t vga_entry(char c) {
    return ((uint16_t)color << 8) | (uint8_t)c;
}

static void vga_hide_cursor(void) {
    outb(0x3D4, 0x0A);
    outb(0x3D5, 0x20);
}

static uint32_t fb_color(uint8_t idx) {
    return vga_palette[idx & 0x0F];
}

static void fb_putpixel(uint32_t x, uint32_t y, uint32_t pixel) {
    if (!fb_active || x >= fb_width || y >= fb_height) return;
    fb_pixels[y * fb_stride + x] = pixel;
}

static void fb_fill_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t pixel) {
    if (!fb_active) return;
    for (uint32_t yy = 0; yy < h && (y + yy) < fb_height; ++yy) {
        for (uint32_t xx = 0; xx < w && (x + xx) < fb_width; ++xx) {
            fb_putpixel(x + xx, y + yy, pixel);
        }
    }
}

static void fb_scroll(void) {
    if (!fb_active || fb_rows <= 1) return;
    uint32_t row_pixels = fb_stride * FB_CELL_H;
    uint32_t copy_rows = (uint32_t)(fb_rows - 1) * FB_CELL_H;
    for (uint32_t y = 0; y < copy_rows; ++y) {
        uint32_t* dst = (uint32_t*)((uint8_t*)fb_pixels + (y * fb_stride * 4u));
        uint32_t* src = (uint32_t*)((uint8_t*)fb_pixels + ((y + FB_CELL_H) * fb_stride * 4u));
        for (uint32_t x = 0; x < fb_stride; ++x) dst[x] = src[x];
    }
    fb_fill_rect(0, (uint32_t)(fb_rows - 1) * FB_CELL_H, fb_width, FB_CELL_H, fb_color(color >> 4));
}

static void fb_draw_char(uint32_t x, uint32_t y, char c) {
    uint8_t glyph_index = (c >= 32 && c < 128) ? (uint8_t)(c - 32) : (uint8_t)('?' - 32);
    uint32_t fg = fb_color(color & 0x0F);
    uint32_t bg = fb_color(color >> 4);
    for (uint32_t row = 0; row < 8; ++row) {
        uint8_t bits = font8x8_basic[glyph_index][row];
        for (uint32_t col = 0; col < 8; ++col) {
            uint32_t pixel = (bits & (1u << col)) ? fg : bg;
            fb_putpixel(x + col, y + row, pixel);
        }
    }
}

static void fb_clear(void) {
    if (!fb_active) return;
    uint32_t bg = fb_color(color >> 4);
    for (uint32_t y = 0; y < fb_height; ++y) {
        for (uint32_t x = 0; x < fb_width; ++x) {
            fb_pixels[y * fb_stride + x] = bg;
        }
    }
}

static void fb_init(const boot_info_t* boot) {
    fb_active = 0;
    fb_pixels = 0;
    fb_width = fb_height = fb_stride = 0;
    fb_cols = fb_rows = 0;

    if (!boot) return;
    if (boot->framebuffer.framebuffer_base == 0 || boot->framebuffer.width == 0 || boot->framebuffer.height == 0) return;

    fb_pixels = (volatile uint32_t*)(uintptr_t)boot->framebuffer.framebuffer_base;
    fb_width = boot->framebuffer.width;
    fb_height = boot->framebuffer.height;
    fb_stride = boot->framebuffer.pixels_per_scanline;
    fb_cols = (int)(fb_width / FB_CELL_W);
    fb_rows = (int)(fb_height / FB_CELL_H);
    if (fb_cols <= 0 || fb_rows <= 0) {
        fb_pixels = 0;
        return;
    }
    fb_active = 1;
}

static void vga_scroll(void) {
    if (cy < VGA_ROWS) return;
    for (int y = 1; y < VGA_ROWS; ++y) {
        for (int x = 0; x < VGA_COLS; ++x) {
            VGA_MEM[(y - 1) * VGA_COLS + x] = VGA_MEM[y * VGA_COLS + x];
        }
    }
    for (int x = 0; x < VGA_COLS; ++x) VGA_MEM[(VGA_ROWS - 1) * VGA_COLS + x] = ((uint16_t)color << 8) | ' ';
    cy = VGA_ROWS - 1;
}

void console_init(const boot_info_t* boot) {
    fb_init(boot);
    console_clear();
    vga_hide_cursor();
    /* register quiesce callback */
    quiesce_register(console_quiesce_cb);
}

void console_clear(void) {
    cx = cy = 0;
    if (fb_active) fb_clear();
    for (int i = 0; i < VGA_COLS * VGA_ROWS; ++i) VGA_MEM[i] = ((uint16_t)color << 8) | ' ';
}

void console_set_color(uint8_t fg, uint8_t bg) {
    color = (bg << 4) | (fg & 0x0F);
}

static void fb_newline(void) {
    if (!fb_active) return;
    cx = 0;
    cy++;
    if (cy >= fb_rows) {
        fb_scroll();
        cy = fb_rows - 1;
    }
}

void console_putc(char c) {
    console_wait_quiesce();
    if (fb_active) {
        if (c == '\n') {
            fb_newline();
            return;
        }
        if (c == '\r') {
            cx = 0;
            return;
        }
        if (c == '\b') {
            if (cx > 0) {
                cx--;
                fb_fill_rect((uint32_t)cx * FB_CELL_W, (uint32_t)cy * FB_CELL_H, FB_CELL_W, FB_CELL_H, fb_color(color >> 4));
            }
            return;
        }
        fb_draw_char((uint32_t)cx * FB_CELL_W, (uint32_t)cy * FB_CELL_H, c);
        if (++cx >= fb_cols) fb_newline();
        return;
    }

    if (c == '\n') {
        cx = 0;
        cy++;
        vga_scroll();
        return;
    }
    if (c == '\r') {
        cx = 0;
        return;
    }
    if (c == '\b') {
        if (cx > 0) {
            cx--;
            VGA_MEM[cy * VGA_COLS + cx] = vga_entry(' ');
        }
        return;
    }
    VGA_MEM[cy * VGA_COLS + cx] = vga_entry(c);
    if (++cx >= VGA_COLS) {
        cx = 0;
        cy++;
        vga_scroll();
    }
}

void console_write(const char* s) {
    while (*s) console_putc(*s++);
}

void console_writeln(const char* s) {
    console_write(s);
    console_putc('\n');
}
